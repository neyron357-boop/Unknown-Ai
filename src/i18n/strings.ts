const DICTS: Record<Lang, Record<StringKey, string>> = { ru, en };

export function translate(lang: Lang, key: StringKey): string {
  return DICTS[lang][key] ?? ru[key] ?? key;
}

/** React hook: re-renders when the language changes. */
export function useT(): (key: StringKey) => string {
  const lang = useSettings((s) => s.lang);
  return (key) => translate(lang, key);
}

/** Non-reactive translation for game code. */
export function t(key: StringKey): string {
  return translate(useSettings.getState().lang, key);
}
